def preprocess_ascii_for_clip(ascii_art, font_path=font_path, font_size=12):
    # can't lead custom font, I'm too lazy to change it so we use default font

    # Create an image from ASCII art
    try:
        font = ImageFont.truetype(font_path, size=font_size)
    except IOError:
        font = ImageFont.load_default()
        # print("custom font failed, loading default font")
    image = Image.new('RGB', (800, 600), color=(0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.text((10, 10), ascii_art, fill=(255, 255, 255), font=font)

    # Crop, convert to grayscale, blur, and normalize
    bbox = image.getbbox()
    cropped_image = image.crop(bbox) if bbox else image
    grayscale_image = cropped_image.convert("L")

    # reduced the blur when turning text into images - too much blurred image may be contributing to image homogeneity
    # removed blur due to representation collapse
    blurred_image = grayscale_image.filter(ImageFilter.GaussianBlur(0))
    normalized_image = np.array(blurred_image) / 255.0

    return Image.fromarray((normalized_image * 255).astype(np.uint8))


def extract_integer_from_tensor(input_string):
    return float(input_string.replace("tensor", "").replace("(", "").replace(")", "").replace("[", "").replace("]", ""))


def calculate_clip_similarity(image1, image2):
    inputs = processor(images=[image1, image2], return_tensors="pt", padding=True)
    with torch.no_grad():
        image_features = model.get_image_features(**inputs)
    cosine_similarity = torch.nn.functional.cosine_similarity(
        image_features[0].unsqueeze(0), image_features[1].unsqueeze(0), dim=1
    )
    return extract_integer_from_tensor(str(cosine_similarity[0]))

