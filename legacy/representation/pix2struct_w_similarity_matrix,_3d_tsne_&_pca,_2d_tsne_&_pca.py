def inspect_embeddings_with_tsne(loaded_model, ascii_arts, max_classes=731, num_images_per_class=3):
    # Sample ASCII arts and ensure the number of classes does not exceed the maximum
    sampled_ascii_arts = sample_classes_with_fixed_count(ascii_arts, max_classes=max_classes, num_images_per_class=num_images_per_class)
    labels = [art['class'] for art in sampled_ascii_arts]

    # Group embeddings by class for averaging
    embeddings_dict = defaultdict(list)

    for art in sampled_ascii_arts:
        inputs = preprocess_ascii_for_pix2struct(art['ascii_art'])
        with torch.no_grad():
            embeddings = loaded_model(**inputs).last_hidden_state.mean(dim=1)
        embeddings_dict[art['class']].append(embeddings.numpy().flatten())  # Flatten for PCA

    # Average the embeddings for each class
    embeddings_list = []
    unique_labels = []
    for label, embeddings in embeddings_dict.items():
        averaged_embedding = np.mean(embeddings, axis=0)
        embeddings_list.append(averaged_embedding)
        unique_labels.append(label)

    # Visualize PCA
    print("Visualizing 2D PCA:")
    visualize_embeddings(embeddings_list, unique_labels, title="PCA Visualization")

    # Normalize embeddings
    normalized_embeddings_list = normalize_embeddings(embeddings_list)

    # Visualize t-SNE
    print("Visualizing 2D t-SNE:")
    visualize_tsne_embeddings(normalized_embeddings_list, unique_labels, title="t-SNE Visualization")

