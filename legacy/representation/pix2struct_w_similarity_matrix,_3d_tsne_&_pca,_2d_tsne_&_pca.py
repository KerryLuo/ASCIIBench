# Sample ASCII arts from all available classes, up to a maximum number
def sample_classes_with_fixed_count(ascii_arts, max_classes=731, num_images_per_class=3):
    class_to_ascii = defaultdict(list)

    # Group ASCII arts by class
    for art in ascii_arts:
        class_to_ascii[art['class']].append(art)

    # Calculate the actual number of available classes
    total_classes = len(class_to_ascii)

    # Ensure the number of sampled classes doesn't exceed max_classes
    num_classes_to_sample = min(max_classes, total_classes)

    # Randomly select classes (up to num_classes_to_sample)
    selected_classes = random.sample(list(class_to_ascii.keys()), num_classes_to_sample)

    sampled_ascii = []

    # Sample multiple images per class
    for ascii_class in selected_classes:
        ascii_samples = class_to_ascii[ascii_class]
        samples_to_take = min(len(ascii_samples), num_images_per_class)
        sampled_ascii.extend(random.sample(ascii_samples, samples_to_take))

    return sampled_ascii

