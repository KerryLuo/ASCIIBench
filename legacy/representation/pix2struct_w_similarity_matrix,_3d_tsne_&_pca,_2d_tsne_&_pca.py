def inspect_embeddings_with_tsne(loaded_model, ascii_arts, num_samples=15, pca_components=2, tsne_components=2):
    while True:
        selected_ascii_arts = random.sample(ascii_arts, num_samples)
        labels = [art['class'] for art in selected_ascii_arts]
        if len(set(labels)) >= 2 and len(set(labels)) < num_samples:
            break

    embeddings_list = []
    for art in selected_ascii_arts:
        inputs = preprocess_ascii_for_pix2struct(art['ascii_art'])
        with torch.no_grad():
            embeddings = loaded_model(**inputs).last_hidden_state.mean(dim=1)
        embeddings_list.append(embeddings.numpy().flatten())  # Flatten for PCA

    # Visualize PCA before and after normalization
    print(f"Visualizing {pca_components}D PCA before normalization:")
    visualize_embeddings(embeddings_list, labels, pca_components=pca_components, title="Before Normalization")

    normalized_embeddings_list = normalize_embeddings(embeddings_list)

    print(f"Visualizing {pca_components}D PCA after normalization:")
    visualize_embeddings(normalized_embeddings_list, labels, pca_components=pca_components, title="After Normalization")

    # Visualize t-SNE before and after normalization
    print(f"Visualizing {tsne_components}D t-SNE before normalization:")
    visualize_tsne_embeddings(embeddings_list, labels, tsne_components=tsne_components, title="Before Normalization")

    print(f"Visualizing {tsne_components}D t-SNE after normalization:")
    visualize_tsne_embeddings(normalized_embeddings_list, labels, tsne_components=tsne_components, title="After Normalization")

