# Function to calculate similarity using Pix2Struct
def calculate_pix2struct_similarity(inputs_image1, inputs_image2, model):
    with torch.no_grad():
        image1_features = model(**inputs_image1).last_hidden_state.mean(dim=1)
        image2_features = model(**inputs_image2).last_hidden_state.mean(dim=1)

    image1_features = image1_features / image1_features.norm(dim=1, keepdim=True)
    image2_features = image2_features / image2_features.norm(dim=1, keepdim=True)

    similarity = torch.nn.functional.cosine_similarity(image1_features, image2_features)

    return similarity.item()

