def calculate_distance_metrics(outputs_anchor, outputs_positive, outputs_negative):
    distance_positive = (outputs_anchor - outputs_positive).pow(2).sum(1)
    distance_negative = (outputs_anchor - outputs_negative).pow(2).sum(1)
    return distance_positive.mean().item(), distance_negative.mean().item()

# Triplet loss function
def triplet_loss(anchor, positive, negative, margin=1.0):
    distance_positive = (anchor - positive).pow(2).sum(1)
    distance_negative = (anchor - negative).pow(2).sum(1)
    losses = torch.relu(distance_positive - distance_negative + margin)
    return losses.mean()

