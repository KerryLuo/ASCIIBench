# Function to perform t-SNE
def visualize_tsne_embeddings(embeddings_list, labels, tsne_components=2, title="t-SNE Visualization"):
    # Convert the list of embeddings to a NumPy array
    embeddings_array = np.array(embeddings_list)

    # Dynamically adjust perplexity based on the number of samples
    perplexity = min(30, embeddings_array.shape[0] - 1)

    tsne = TSNE(n_components=tsne_components, perplexity=perplexity, n_iter=1000, random_state=42)
    reduced_embeddings = tsne.fit_transform(embeddings_array)  # Use the NumPy array here

    plt.figure(figsize=(10, 8))

    if tsne_components == 2:
        for i, label in enumerate(labels):
            plt.scatter(reduced_embeddings[i, 0], reduced_embeddings[i, 1], label=label)
        plt.title(f"2D t-SNE - {title}")
        plt.legend()
        plt.show()

    elif tsne_components == 3:
        fig = plt.figure(figsize=(10, 8))
        ax = fig.add_subplot(111, projection='3d')
        for i, label in enumerate(labels):
            ax.scatter(reduced_embeddings[i, 0], reduced_embeddings[i, 1], reduced_embeddings[i, 2], label=label)
        ax.set_title(f"3D t-SNE - {title}")
        ax.legend()
        plt.show()

# Visualize embeddings using 2D or 3D PCA
def visualize_embeddings(embeddings_list, labels, pca_components=2, title="PCA Visualization"):
    pca = PCA(n_components=pca_components)
    reduced_embeddings = pca.fit_transform(embeddings_list)

    # Explained Variance and Cumulative Variance
    explained_variance = pca.explained_variance_ratio_
    cumulative_variance = np.cumsum(explained_variance)

    print(f"Explained Variance by Components: {explained_variance}")
    print(f"Cumulative Variance: {cumulative_variance}")

    if pca_components == 2:
        plt.figure(figsize=(10, 8))
        for i, label in enumerate(labels):
            plt.scatter(reduced_embeddings[i, 0], reduced_embeddings[i, 1], label=label)
        plt.title(f"2D PCA - {title}")
        plt.legend()
        plt.show()

    elif pca_components == 3:
        fig = plt.figure(figsize=(10, 8))
        ax = fig.add_subplot(111, projection='3d')
        for i, label in enumerate(labels):
            ax.scatter(reduced_embeddings[i, 0], reduced_embeddings[i, 1], reduced_embeddings[i, 2], label=label)
        ax.set_title(f"3D PCA - {title}")
        ax.legend()
        plt.show()

    # Ensure there are at least two unique labels before calculating the Silhouette Score
    if len(set(labels)) > 1:
        silhouette = silhouette_score(reduced_embeddings, labels)
        print(f"Silhouette Score for {pca_components}D PCA: {silhouette}")
    else:
        print("Not enough unique labels to calculate the Silhouette Score.")

    # Visualize the loading matrix
    loadings = pca.components_.T * np.sqrt(pca.explained_variance_)
    print(f"PCA Loadings: {loadings}")

