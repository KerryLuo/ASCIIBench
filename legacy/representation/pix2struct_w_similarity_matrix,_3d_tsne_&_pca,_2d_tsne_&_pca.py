# Function to create triplets
def create_triplets(data):
    triplets = []
    # Check if data is empty
    if not data:
        return triplets

    for anchor in data:
        same_class = [d for d in data if d['class'] == anchor['class'] and d['unique_id'] != anchor['unique_id']]
        different_class = [d for d in data if d['class'] != anchor['class']]

        # Check if there are enough items for positive and negative examples
        if not same_class or not different_class:
            continue

        positive = random.choice(same_class)
        negative = random.choice(different_class)
        triplets.append((anchor, positive, negative))

    return triplets



