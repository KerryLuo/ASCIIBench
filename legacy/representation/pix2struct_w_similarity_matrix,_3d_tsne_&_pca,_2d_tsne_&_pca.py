# Function to visualize t-SNE embeddings
def visualize_tsne_embeddings(embeddings_list, labels, title="t-SNE Visualization"):
    embeddings_array = np.array(embeddings_list)
    perplexity = min(30, embeddings_array.shape[0] - 1)

    tsne = TSNE(n_components=2, perplexity=perplexity, n_iter=1000, random_state=42)
    reduced_embeddings = tsne.fit_transform(embeddings_array)

    plt.figure(figsize=(10, 8))
    unique_labels = list(set(labels))
    colors = sns.color_palette("hsv", len(unique_labels))  # Generate a color palette

    for i, label in enumerate(labels):
        label_index = unique_labels.index(label)
        plt.scatter(reduced_embeddings[i, 0], reduced_embeddings[i, 1], color=colors[label_index], label=label, alpha=0.7)

    plt.title(f"2D t-SNE - {title}")
    plt.legend()
    plt.show()

