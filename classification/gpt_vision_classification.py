def preprocess_ascii_for_clip(ascii_art, font_path="Courier.ttf", font_size=12):
    # Create an image from ASCII art
    try:
        # Attempt to use a specific font
        font = ImageFont.truetype("Courier.ttf", size=font_size)
    except IOError:
        # Fallback to the default PIL font if specific font is not found
        font = ImageFont.load_default()
    image = Image.new('RGB', (800, 600), color=(0, 0, 0))  # Create a black background image
    draw = ImageDraw.Draw(image)
    draw.text((10, 10), ascii_art, fill=(255, 255, 255), font=font)  # White text on black background

    # Crop to remove unnecessary whitespace
    bbox = image.getbbox()
    cropped_image = image.crop(bbox) if bbox else image

    # Convert to grayscale
    grayscale_image = cropped_image.convert("L")

    # Apply a slight blur
    blurred_image = grayscale_image.filter(ImageFilter.GaussianBlur(0))

    # Normalize the pixel values if required by the model (e.g., scale between 0 and 1)
    # Here, we assume a normalization of 0 to 1 for grayscale images
    normalized_image = np.array(blurred_image) / 255.0

    final_image = Image.fromarray((normalized_image * 255).astype(np.uint8))

