def dedupe_dataset(dataset, key=None, save_path=None):
    """
    Remove duplicates from a list of dicts.

    Args:
        dataset (list[dict]): your records
        key (str|None): if provided, consider records duplicates when dataset[i][key] repeats.
                        if None, the entire dict is used for duplicate detection.
        save_path (str|None): if provided, saves the filtered dataset as JSONL

    Returns:
        filtered (list[dict]): dataset with duplicates removed (first occurrence kept)
    """
    seen = set()
    filtered = []
    dup_count = 0

    for record in dataset:
        if key is None:
            # Use a stable serialization of the whole dict as the identity
            try:
                identity = json.dumps(record, sort_keys=True, ensure_ascii=False)
            except TypeError:
                # Fallback if there are unserializable types
                identity = repr(record)
        else:
            # Use the value under `key` as identity; if key missing, treat the whole dict as identity
            if key in record:
                identity = record[key]
            else:
                try:
                    identity = ("__MISSING_KEY__", json.dumps(record, sort_keys=True, ensure_ascii=False))
                except TypeError:
                    identity = ("__MISSING_KEY__", repr(record))

        if identity in seen:
            dup_count += 1
            continue

        seen.add(identity)
        filtered.append(record)

    print(f"Removed {dup_count} duplicates. New length: {len(filtered)}")

    if save_path:
        with open(save_path, "w", encoding="utf-8") as f:
            for row in filtered:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        print(f"💾 Saved to {save_path}")

    return filtered

