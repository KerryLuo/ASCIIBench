def validate_jsonl(path, max_preview=200):
    """
    Validate a JSONL file. Prints the first few malformed lines (if any).
    """
    errors = 0
    with open(path, "r", encoding="utf-8") as f:
        for i, line in enumerate(f, start=1):
            s = line.strip()
            if not s:
                continue
            try:
                json.loads(s)
            except JSONDecodeError as e:
                errors += 1
                preview = s[:max_preview]
                print(f"[ERROR] line {i}: {e.msg} at pos {e.pos}. Preview: {preview!r}")
    if errors == 0:
        print("✅ JSONL looks valid (each non-empty line parsed).")
    else:
        print(f"❌ Found {errors} malformed line(s). Fix or use lenient loader.")
    return errors == 0


def _split_concatenated_objects(text):
    """
    Split a string that may contain multiple concatenated JSON objects into a list of JSON strings.
    Respects strings and escapes. Returns [] if it can't split into valid objects.
    """
    objs = []
    buf = []
    depth = 0
    in_str = False
    esc = False

    def flush():
        s = "".join(buf).strip()
        if s:
            objs.append(s)
        buf.clear()

    for ch in text:
        buf.append(ch)
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
        else:
            if ch == '"':
                in_str = True
            elif ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    flush()

    # Only valid if we ended cleanly at depth 0 and produced at least one object
    if depth != 0 or not objs:
        return []
    return objs


def load_jsonl(path, allow_concatenated_per_line=True, skip_blank=True, strict=False):
    """
    Load a JSONL file into a list of dicts.

    - Parses each non-blank line with json.loads.
    - If a line fails to parse and allow_concatenated_per_line=True,
      it tries to split that single line into multiple JSON objects.
    - If strict=True, raises on first error; otherwise raises after trying concatenation.

    Returns: list[dict]
    """
    records = []
    with open(path, "r", encoding="utf-8") as f:
        for i, line in enumerate(f, start=1):
            s = line.rstrip("\n")
            if skip_blank and not s.strip():
                continue
            try:
                records.append(json.loads(s))
            except JSONDecodeError as e:
                if not allow_concatenated_per_line:
                    msg = f"Malformed JSON at line {i}: {e.msg} (pos {e.pos})"
                    if strict:
                        raise JSONDecodeError(msg, s, e.pos)
                    else:
                        raise JSONDecodeError(msg, s, e.pos)
                # Try splitting concatenated objects on this line
                parts = _split_concatenated_objects(s)
                if parts:
                    for p in parts:
                        records.append(json.loads(p))
                else:
                    msg = f"Malformed JSON at line {i}: {e.msg} (pos {e.pos})"
                    if strict:
                        raise JSONDecodeError(msg, s, e.pos)
                    else:
                        # If you prefer to skip bad lines instead of raising, replace the raise with a print+continue
                        raise JSONDecodeError(msg, s, e.pos)
    return records

