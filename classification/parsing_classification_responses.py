def remove_ascii_with_phrase(dataset, phrase="The Great Ascii Art Library", save_path=None, case_insensitive=True):
    """
    Remove records whose 'ascii_art' contains a given phrase.

    Args:
        dataset (list[dict]): your records
        phrase (str): phrase to search for
        save_path (str|None): if provided, saves the cleaned dataset as JSONL
        case_insensitive (bool): whether to ignore case when searching

    Returns:
        cleaned (list[dict]): dataset with those ascii_art entries removed
    """
    before = len(dataset)

    def contains_phrase(text, phrase):
        if text is None:
            return False
        if case_insensitive:
            return phrase.lower() in text.lower()
        return phrase in text

    cleaned = [rec for rec in dataset if not contains_phrase(rec.get("ascii_art", ""), phrase)]
    removed = before - len(cleaned)

    print(f"Removed {removed} records containing phrase '{phrase}'. New length: {len(cleaned)}")

    if save_path:
        with open(save_path, "w", encoding="utf-8") as f:
            for row in cleaned:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        print(f"💾 Saved cleaned dataset to {save_path}")

    return cleaned

