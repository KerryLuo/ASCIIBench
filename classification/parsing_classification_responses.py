def clean_gen_with_master(gen_dataset, master_dataset, save_path=None):
    """
    Deduplicate gen_dataset by 'ascii_art' and enforce class consistency with master_dataset.
    Only keeps ascii_art entries that exist in master_dataset.

    Rules:
      - Build a mapping from master: ascii_art -> class (resolve conflicts by majority vote).
      - For each ascii_art group in gen_dataset:
          * If ascii_art in master:
              - Keep exactly one record whose 'actual_class' == master class if possible.
              - Otherwise keep the first record and set its 'actual_class' to the master class.
          * If ascii_art not in master:
              - Discard it entirely.

    Returns:
      cleaned_gen (list[dict])
    """
    # 1) Build master mapping: ascii_art -> class (resolve conflicts by majority vote)
    master_classes = defaultdict(list)
    for rec in master_dataset:
        a = rec.get("ascii_art")
        c = rec.get("class")
        if a is not None:
            master_classes[a].append(c)

    ascii_to_master_class = {}
    conflicts = 0
    for a, cls_list in master_classes.items():
        counts = Counter(cls_list)
        if len(counts) > 1:
            conflicts += 1
        master_cls = counts.most_common(1)[0][0]  # majority vote
        ascii_to_master_class[a] = master_cls

    if conflicts:
        print(f"⚠️  Master conflicts: {conflicts} ascii_art values map to multiple classes. "
              f"Resolved by majority vote.")

    # 2) Group gen by ascii_art
    gen_groups = defaultdict(list)
    for rec in gen_dataset:
        a = rec.get("ascii_art")
        if a is not None:
            gen_groups[a].append(rec)

    # 3) Build cleaned list
    cleaned = []
    adjusted = 0
    matched = 0
    dropped = 0

    for a, records in gen_groups.items():
        if a not in ascii_to_master_class:
            dropped += len(records)
            continue  # remove ascii_art not in master

        target_cls = ascii_to_master_class[a]

        # Try to find a record whose actual_class already matches master class
        chosen = None
        for r in records:
            if r.get("actual_class") == target_cls:
                chosen = r
                break

        if chosen is None:
            # No exact match; copy first and fix actual_class
            base = records[0].copy()
            base["actual_class"] = target_cls
            cleaned.append(base)
            adjusted += 1
        else:
            cleaned.append(chosen)
            matched += 1

    print(f"Cleaned gen_dataset: {len(cleaned)} unique ascii_art entries kept "
          f"out of {len(gen_dataset)} rows.")
    print(f" - Matched master class without change: {matched}")
    print(f" - Adjusted actual_class to match master: {adjusted}")
    print(f" - Dropped (not in master): {dropped}")

    if save_path:
        with open(save_path, "w", encoding="utf-8") as f:
            for row in cleaned:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        print(f"💾 Saved cleaned gen dataset to {save_path}")

    return cleaned

