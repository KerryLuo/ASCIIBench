def validate_jsonl(path, max_preview=120):
    """Return (ok: bool, errors: list[str]) and avoid raising."""
    errors = []
    with open(path, "r", encoding="utf-8") as f:
        for i, line in enumerate(f, start=1):
            s = line.strip()
            if not s:
                continue
            try:
                json.loads(s)
            except JSONDecodeError as e:
                preview = s[:max_preview].replace("\n", "\\n")
                errors.append(f"[ERROR] {os.path.basename(path)} line {i}: {e.msg} at pos {e.pos}. Preview: {preview!r}")
    return (len(errors) == 0, errors)


def _split_concatenated_objects(text):
    """
    Split a string that may contain multiple concatenated JSON objects into a list of JSON strings.
    Respects strings and escapes. Returns [] if it can't split into valid objects.
    """
    objs, buf = [], []
    depth = 0
    in_str = False
    esc = False

    def flush():
        s = "".join(buf).strip()
        if s:
            objs.append(s)
        buf.clear()

    for ch in text:
        buf.append(ch)
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
        else:
            if ch == '"':
                in_str = True
            elif ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    flush()

    if depth != 0 or not objs:
        return []
    return objs


def load_lenient_jsonl(path):
    """
    Load JSONL leniently:
      - Try line-by-line parsing
      - If a line fails, attempt to split that single line into concatenated JSON objects
    Returns list of dicts; raises if a line cannot be repaired.
    """
    records = []
    with open(path, "r", encoding="utf-8") as f:
        lines = f.readlines()

    # Fast path: if more than 1 line and all lines parse, just return
    all_ok = True
    tmp = []
    for i, line in enumerate(lines, start=1):
        s = line.strip()
        if not s:
            continue
        try:
            tmp.append(json.loads(s))
        except JSONDecodeError:
            all_ok = False
            break
    if all_ok:
        return tmp

    # Slow path: handle concatenated objects on any offending line
    for i, line in enumerate(lines, start=1):
        s = line.strip()
        if not s:
            continue
        try:
            records.append(json.loads(s))
        except JSONDecodeError as e:
            parts = _split_concatenated_objects(s)
            if parts:
                for p in parts:
                    records.append(json.loads(p))
            else:
                raise JSONDecodeError(
                    f"Cannot parse or repair line {i}: {e.msg}", s, e.pos
                )
    return records


def repair_jsonl_file(in_path, out_path=None, make_backup=True):
    """
    Read a possibly-broken JSONL and rewrite it canonically (1 object per line).
    If out_path is None, overwrite in_path (optionally write .bak).
    Returns number of records written.
    """
    if out_path is None:
        out_path = in_path

    # Load with lenient parser
    records = load_lenient_jsonl(in_path)

    # Backup if overwriting
    if out_path == in_path and make_backup:
        bak_path = in_path + ".bak"
        if not os.path.exists(bak_path):
            with open(in_path, "rb") as src, open(bak_path, "wb") as dst:
                dst.write(src.read())

    # Write canonical JSONL (newline per object)
    with open(out_path, "w", encoding="utf-8") as f:
        for obj in records:
            f.write(json.dumps(obj, ensure_ascii=False) + "\n")

    return len(records)


