def align_by_ascii_art(master_dataset, gen_dataset, save_path=None, sample_report=0):
    """
    Keep ONLY those dicts from gen_dataset whose 'ascii_art' exists in master_dataset.
    Prints containment status and examples of missing/excess items.

    Returns:
        aligned_dataset (list[dict])
    """
    # Build sets of ascii_art (skip records missing the key)
    master_ascii = {d["ascii_art"] for d in master_dataset if "ascii_art" in d}
    gen_ascii    = {d["ascii_art"] for d in gen_dataset if "ascii_art" in d}

    # Containment checks
    missing_in_gen = master_ascii - gen_ascii      # in master but not in gen
    extras_in_gen  = gen_ascii - master_ascii      # in gen but not in master

    if not missing_in_gen:
        print("✅ gen_dataset contains ALL ascii_art entries from master_dataset.")
    else:
        print(f"❌ Missing in gen_dataset: {len(missing_in_gen)} items that appear in master_dataset.")
        for ex in list(missing_in_gen)[:sample_report]:
            print("   - MISSING:", ex)

    if extras_in_gen:
        print(f"ℹ️  gen_dataset has {len(extras_in_gen)} EXTRA items not in master_dataset.")
        for ex in list(extras_in_gen)[:sample_report]:
            print("   - EXTRA:", ex[:120].replace("\n", "\\n") + ("..." if len(ex) > 120 else ""))
    else:
        print("✅ No extras in gen_dataset.")

    # Align: keep gen records whose ascii_art is in master
    before = len(gen_dataset)
    aligned_dataset = [d for d in gen_dataset if d.get("ascii_art") in master_ascii]
    after = len(aligned_dataset)
    print(f"Trimmed gen_dataset from {before} → {after} (removed {before - after}).")

    # Optionally save as JSONL
    if save_path:
        with open(save_path, "w", encoding="utf-8") as f:
            for row in aligned_dataset:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        print(f"💾 Saved aligned_dataset to {save_path}")

    return aligned_dataset

