def find_duplicates_with_classes(dataset, key="ascii_art", class_key="class", sample_report=3):
    """
    Find and display duplicates in a dataset by a given key,
    also listing the different classes for those duplicates.

    Args:
        dataset (list[dict]): list of dict records
        key (str): key to check for duplicates (e.g., "ascii_art")
        class_key (str): class/label key (e.g., "class")
        sample_report (int): how many sample records per duplicate to show

    Returns:
        dict: {key_value: [list of records]}
    """
    # count occurrences
    counts = Counter(d.get(key) for d in dataset if key in d)

    # collect duplicates
    duplicates = defaultdict(list)
    for d in dataset:
        if key in d and counts[d[key]] > 1:
            duplicates[d[key]].append(d)

    print(f"Found {len(duplicates)} duplicated '{key}' entries.")
    for i, (val, records) in enumerate(duplicates.items()):
        print(f"\nDuplicate {i+1}: appears {len(records)} times")
        preview = val[:120].replace("\n", "\\n") if isinstance(val, str) else str(val)
        print("  ascii_art preview:", preview + ("..." if len(preview) == 120 else ""))

        # collect distinct classes
        class_set = {rec.get(class_key, "MISSING") for rec in records}
        print(f"  Distinct classes: {len(class_set)} → {class_set}")

        # show sample records
        for rec in records[:sample_report]:
            print("   - sample record:", json.dumps(rec, ensure_ascii=False)[:200])
        if len(records) > sample_report:
            print(f"   ... and {len(records) - sample_report} more")

    return duplicates


