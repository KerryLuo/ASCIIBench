def resolve_conflicting_ascii_classes(dataset, save_path=None, sample_records_to_show=0):
    """
    Interactively resolve duplicates where the same ascii_art has different 'class' values.

    For each ascii_art with conflicting classes:
      - Prints the full ascii_art (preserves newlines).
      - Prints class options labeled 1 and 2 (and more if they exist).
      - If user types '1' -> keep a single record with class option 1; remove others for that ascii.
      - If user types '2' -> keep a single record with class option 2; remove others for that ascii.
      - If user types anything else -> keep a single record with 'class' set to the typed value; remove others.

    Assumes record format includes keys:
        ['class', 'unique_id', 'file_name', 'ascii_art']

    Args:
        dataset (list[dict]): input records
        save_path (str|None): if provided, saves cleaned dataset as JSONL
        sample_records_to_show (int): optionally print full records in each group for debugging

    Returns:
        cleaned (list[dict]): dataset with conflicts resolved (one record per ascii_art)
    """
    # Group records by ascii_art
    by_ascii = defaultdict(list)
    for rec in dataset:
        ascii_text = rec.get("ascii_art")
        if ascii_text is None:
            # Keep entries without ascii_art untouched (append later)
            continue
        by_ascii[ascii_text].append(rec)

    cleaned = []
    kept_ascii = set()
    total_conflicts = 0
    changes_made = 0

    # First pass: handle groups with conflicts (multiple distinct classes)
    for ascii_text, records in by_ascii.items():
        classes = list({r.get("class") for r in records})
        if len(classes) <= 1:
            # No conflict: keep the first record (you can keep all duplicates here if you prefer)
            cleaned.append(records[0])
            kept_ascii.add(ascii_text)
            continue

        total_conflicts += 1

        # Present interactive choice
        print("\n" + "=" * 80)
        print(f"Conflict #{total_conflicts}: ascii_art appears under {len(classes)} classes")
        print("\nASCII IMAGE (full):\n")
        print(ascii_text)  # preserve newlines exactly
        print("\nClasses:")

        # Sort classes just for deterministic labeling
        classes_sorted = sorted(classes, key=lambda x: "" if x is None else str(x))
        for idx, cls in enumerate(classes_sorted, start=1):
            print(f"  {idx}. {cls}")

        if sample_records_to_show > 0:
            print("\nSample records:")
            for r in records[:sample_records_to_show]:
                print(json.dumps(r, ensure_ascii=False))

        # Prompt user
        choice = input(
            "\nType 1 or 2 to choose that class.\n"
            "If you type anything else, ALL duplicates will be removed and ONE record will be kept with 'class' set to your input.\n"
            "Your choice: "
        ).strip()

        if choice in {"1", "2"}:
            # Keep the chosen class (if more classes exist, ignore them; spec focuses on 1/2)
            idx = int(choice) - 1
            if 0 <= idx < len(classes_sorted):
                chosen_class = classes_sorted[idx]
            else:
                # Fallback: if somehow out of range, default to first class
                chosen_class = classes_sorted[0]
            # Keep first record with chosen_class; drop others
            chosen_record = next((r for r in records if r.get("class") == chosen_class), records[0])
            cleaned.append(chosen_record)
            kept_ascii.add(ascii_text)
            changes_made += 1
            print(f"→ Kept class: {chosen_class}")
        else:
            # Use user-provided class label, keep exactly one record and set its 'class'
            new_class = choice
            base = records[0].copy()
            base["class"] = new_class
            cleaned.append(base)
            kept_ascii.add(ascii_text)
            changes_made += 1
            print(f"→ Reassigned class to: {new_class}")

    # Second pass: add any entries that lacked 'ascii_art' (were skipped in grouping)
    for rec in dataset:
        if rec.get("ascii_art") is None:
            cleaned.append(rec)

    print("\n" + "=" * 80)
    print(f"Conflicts processed: {total_conflicts}")
    print(f"Changes made: {changes_made}")
    print(f"New dataset length: {len(cleaned)}")

    if save_path:
        with open(save_path, "w", encoding="utf-8") as f:
            for row in cleaned:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        print(f"💾 Saved cleaned dataset to {save_path}")

    return cleaned

