def compute_micro_macro_accuracy(dataset: List[Dict[str, Any]]) -> Dict[str, float]:
    """
    Compute micro and macro accuracy for classification results.

    Expects each record in dataset to have:
      - 'actual_class' (str): the gold label
      - 'predicted_class' (str): model prediction
      - 'correct' (bool): whether prediction == gold
      - 'choices' (list[str]): the candidate classes

    Micro = overall accuracy (total correct / total samples).
    Macro = average accuracy across classes (each class weighted equally).
    Pass rate = % of samples where predicted_class was one of the given choices.
    """
    total, correct_total = 0, 0
    per_class = defaultdict(lambda: {"correct": 0, "total": 0})
    pass_count = 0

    for rec in dataset:
        actual = rec.get("actual_class")
        is_correct = bool(rec.get("correct", False))
        choices = rec.get("choices", [])
        pred = rec.get("predicted_class")

        if actual is None:
            continue  # skip malformed entries

        total += 1
        per_class[actual]["total"] += 1
        if is_correct:
            correct_total += 1
            per_class[actual]["correct"] += 1

        # check if prediction was one of the presented choices
        if isinstance(pred, str) and any(
            str(pred).strip().lower() == str(c).strip().lower()
            for c in choices
        ):
            pass_count += 1

    # Micro accuracy = correct / total
    micro = (correct_total / total) if total else 0.0

    # Macro accuracy = mean of per-class accuracies
    class_accs = []
    for cls, cnts in per_class.items():
        if cnts["total"] > 0:
            class_accs.append(cnts["correct"] / cnts["total"])
    macro = (sum(class_accs) / len(class_accs)) if class_accs else 0.0

    pass_rate = (pass_count / total) if total else 0.0

    return {
        "micro_accuracy": micro,
        "macro_accuracy": macro,
        "pass_rate": pass_rate,
        "num_samples": total,
        "num_classes": len(per_class),
    }

