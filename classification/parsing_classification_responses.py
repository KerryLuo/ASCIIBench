def fill_actual_class(dataset: List[Dict], master_dataset: List[Dict]) -> List[Dict]:
    """
    Matches items in dataset with master_dataset using 'ascii_art'.
    Updates 'actual_class' in dataset with 'class' from master_dataset.
    """
    # Create a lookup dictionary from master_dataset for fast matching
    master_lookup = {item["ascii_art"]: item["class"] for item in master_dataset}

    # Update dataset
    for item in dataset:
        ascii_art = item.get("ascii_art")
        if ascii_art in master_lookup:
            item["actual_class"] = master_lookup[ascii_art]

    return dataset

def find_classification(response, choices):
    response = response.split("Classification")[-1]

    counts = {choice: response.count(choice) for choice in choices}

    # Find the maximum count value
    max_count = max(counts.values(), default=0)

    # Get the list of choices with the maximum count
    most_frequent = [choice for choice, count in counts.items() if count == max_count]

    # If there's exactly one choice with the maximum count, return it; otherwise, return False
    return most_frequent[0] if len(most_frequent) == 1 and max_count > 0 else False

