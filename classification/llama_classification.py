def _normalize_ascii(s: str) -> str:
    """Make ASCII art comparable across files: unify newlines, strip trailing spaces, trim ends."""
    if not isinstance(s, str):
        return ""
    s = s.replace("\r\n", "\n").replace("\r", "\n")
    s = "\n".join(line.rstrip() for line in s.split("\n")).strip()
    return s

def _safe_load_jsonl(path: str):
    """Load JSONL; ignore malformed lines gracefully."""
    records = []
    if not os.path.exists(path):
        return records
    with open(path, "r", encoding="utf-8") as f:
        for i, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except Exception as e:
                print(f"[warn] Skipping malformed line {i} in {path}: {e}")
    return records

def build_seen_map_from_logs(log_paths):
    """
    Build a map: normalized_ascii -> actual_class (last seen wins).
    We prefer 'actual_class' if present, fall back to 'class' if needed.
    """
    seen = {}
    count = 0
    for p in log_paths:
        recs = _safe_load_jsonl(p)
        for r in recs:
            art = r.get("ascii_art")
            cls = r.get("actual_class", r.get("class"))
            if art is None or cls is None:
                continue
            key = _normalize_ascii(art)
            seen[key] = cls
            count += 1
    return seen, count

def compute_items_to_run(master_dataset, seen_map):
    """
    master_dataset: list[{'ascii_art':..., 'class':...}]
    seen_map: {normalized_ascii: actual_class_logged}
    Returns a filtered list of items that still need inference:
      - not seen at all, or
      - seen but class mismatch (so we re-run to correct/confirm).
    """
    missing = []
    total = 0
    matched = 0
    mismatched = 0

    for item in master_dataset:
        art = item.get("ascii_art")
        cls = item.get("class")
        if art is None or cls is None:
            continue
        total += 1
        key = _normalize_ascii(art)
        logged_cls = seen_map.get(key, None)
        if logged_cls is None:
            missing.append(item)           # brand new
        elif str(logged_cls) != str(cls):  # mismatch with master label -> re-run
            missing.append(item)
            mismatched += 1
        else:
            matched += 1

    print(f"[filter] master total: {total}")
    print(f"[filter] already covered (matched class): {matched}")
    print(f"[filter] need to run (new or mismatch): {len(missing)} (mismatch count: {mismatched})")
    return missing

