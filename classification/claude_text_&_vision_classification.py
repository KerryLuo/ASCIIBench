# Function to process each JSON object
def process_json_object(obj):
    if 'response' in obj and isinstance(obj['response'], list):
        # Extract the first word from the 'response' list's first element
        first_sentence = obj['response'][0]
        first_word = first_sentence.split()[0].rstrip('.')

        # Assign the first word to 'predicted_class'
        obj['predicted_class'] = first_word

        # Remove the first word and the following period from the 'response'
        obj['response'][0] = first_sentence[len(first_word) + 1:].strip()

        # Compare 'predicted_class' with 'actual_class' (case-insensitive)
        if obj['predicted_class'].lower() == obj['actual_class'].lower():
            obj['correct'] = True
        else:
            obj['correct'] = False
    return obj

