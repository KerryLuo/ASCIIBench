# Function to load triplets from a JSON file, given the full dataset
def load_triplets_from_json(file_path, full_data):
    with open(file_path, 'r') as file:
        triplet_ids = json.load(file)

    # Reconstruct the triplets from the unique IDs
    triplets = []
    for triplet in triplet_ids:
        anchor_id = triplet['anchor']
        positive_id = triplet['positive']
        negative_id = triplet['negative']

        anchor = fetch_data_from_identifier(anchor_id, full_data)
        positive = fetch_data_from_identifier(positive_id, full_data)
        negative = fetch_data_from_identifier(negative_id, full_data)

        if anchor and positive and negative:
            triplets.append((anchor, positive, negative))

    return triplets

