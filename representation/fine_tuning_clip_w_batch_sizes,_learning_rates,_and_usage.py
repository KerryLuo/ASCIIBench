def preprocess_ascii_for_clip(ascii_art, font_path="/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"):
    """
    Reimplementation of create_image_from_ascii with DejaVu Sans Mono.
    White background, black text, fixed image size, explicit cropping + margin.
    """
    image_size = (1600, 1200)
    font_size = 18
    margin = 10

    image = Image.new('RGB', image_size, 'white')
    draw = ImageDraw.Draw(image)
    font = ImageFont.truetype(font_path, font_size)

    # measure line height using a dummy char
    (_, _, _, height) = draw.textbbox((0, 0), "A", font=font)
    line_height = height + 2

    # draw ASCII art line by line
    y_position = 0
    for art_line in ascii_art.split('\n'):
        draw.text((10, y_position), art_line, font=font, fill='black')
        y_position += line_height

    # crop to content + margin
    pixels = image.load()
    width, height = image.size

    def is_row_blank(row):
        return all(pixels[x, row] == (255, 255, 255) for x in range(width))

    def is_column_blank(column):
        return all(pixels[column, y] == (255, 255, 255) for y in range(height))

    top = next((y for y in range(height) if not is_row_blank(y)), None)
    bottom = next((y for y in range(height - 1, -1, -1) if not is_row_blank(y)), None)
    left = next((x for x in range(width) if not is_column_blank(x)), None)
    right = next((x for x in range(width - 1, -1, -1) if not is_column_blank(x)), None)

    if None not in (top, bottom, left, right):
        top = max(0, top - margin)
        bottom = min(height, bottom + margin)
        left = max(0, left - margin)
        right = min(width, right + margin)
        image = image.crop((left, top, right, bottom))

    return image

# Function to create triplets
def create_triplets(data):
    triplets = []
    # Check if data is empty
    if not data:
        return triplets

    for anchor in data:
        same_class = [d for d in data if d['class'] == anchor['class'] and d['unique_id'] != anchor['unique_id']]
        different_class = [d for d in data if d['class'] != anchor['class']]

        # Check if there are enough items for positive and negative examples
        if not same_class or not different_class:
            continue

        positive = random.choice(same_class)
        negative = random.choice(different_class)
        triplets.append((anchor, positive, negative))

    return triplets

