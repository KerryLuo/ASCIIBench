# Note that this function slightly differs from the other notebook since it normalizes the feature vectors.

def calculate_clip_similarity(image1_path, image2_path, model, processor):
    # Load and preprocess the images
    image1 = Image.open(image1_path).convert("RGB")
    image2 = Image.open(image2_path).convert("RGB")
    inputs_image1 = processor(images=image1, return_tensors="pt")
    inputs_image2 = processor(images=image2, return_tensors="pt")

    # Pass the images through the model
    with torch.no_grad():  # No need to track gradients for similarity calculation
        image1_features = model.get_image_features(**inputs_image1)
        image2_features = model.get_image_features(**inputs_image2)

    # Normalize the feature vectors
    image1_features = image1_features / image1_features.norm(dim=1, keepdim=True)
    image2_features = image2_features / image2_features.norm(dim=1, keepdim=True)

    # Calculate cosine similarity
    similarity = torch.nn.functional.cosine_similarity(image1_features, image2_features)

    return similarity.item()

