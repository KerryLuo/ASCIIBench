# Projection head definition (must match training)
class ProjectionHead(nn.Module):
    def __init__(self, dim_in: int, dim_out: int = 512):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(dim_in, dim_out),
            nn.GELU(),
            nn.Linear(dim_out, dim_out),
        )
        # log temperature exists in training, but for feature extraction we only need the net
        self.log_tau = nn.Parameter(torch.log(torch.tensor(0.07)))

    def forward(self, x):
        return self.net(x), self.log_tau

