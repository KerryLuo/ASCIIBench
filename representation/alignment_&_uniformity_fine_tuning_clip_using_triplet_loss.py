# ---- Robust encoder weight loader (handles prefix/no-prefix) ----
def load_encoder_weights(model, ckpt_path):
    sd = torch.load(ckpt_path, map_location='cpu')

    def try_load(no_prefix_sd):
        try:
            model.encoder.load_state_dict(no_prefix_sd, strict=True)
            return True, None
        except Exception as e:
            return False, str(e)

    # Case A: keys look like 'embeddings.*' or 'encoder.layer.*' → load into model.encoder directly
    if any(k.startswith('embeddings.') or k.startswith('encoder.layer.') for k in sd.keys()):
        ok, err = try_load(sd)
        if ok:
            print("Loaded encoder weights (no 'encoder.' prefix).")
            return
        print("Attempt A failed:", err)

    # Case B: keys start with 'encoder.' → strip that prefix to match model.encoder.*
    if all(k.startswith('encoder.') for k in sd.keys()):
        remapped = {k[len('encoder.'):]: v for k, v in sd.items()}
        ok, err = try_load(remapped)
        if ok:
            print("Loaded encoder weights (stripped 'encoder.' prefix).")
            return
        print("Attempt B failed:", err)

    # Fallback: relaxed full-model load (not ideal for analysis, but better than nothing)
    missing, unexpected = model.load_state_dict(sd, strict=False)
    print(f"Fallback relaxed load. Missing: {len(missing)}, Unexpected: {len(unexpected)}")
    if missing: print("  Sample missing:", missing[:8])
    if unexpected: print("  Sample unexpected:", unexpected[:8])

