@torch.no_grad()
def get_features(pil_image, use_projection: bool):
    """
    If use_projection=False:
        return L2-normalized mean-pooled encoder features
    If use_projection=True:
        return L2-normalized projected features (encoder → head)
    """
    inputs = processor(images=pil_image, return_tensors="pt").to(DEVICE)
    enc = model(**inputs, output_hidden_states=False, return_dict=True)
    feat = enc.last_hidden_state.mean(dim=1)  # (1, H)

    if use_projection:
        z, _ = proj_head(feat)                # (1, D)
        vec = torch.nn.functional.normalize(z, p=2, dim=1)
    else:
        vec = torch.nn.functional.normalize(feat, p=2, dim=1)

    return vec.squeeze(0).detach().cpu().numpy()

