@torch.no_grad()
def get_pix2struct_features(pil_image, normalize=L2_NORMALIZE_FEATURES):
    """
    Mean‑pool last_hidden_state from Pix2Struct encoder as an image embedding.
    """
    inputs = processor(images=pil_image, return_tensors="pt")
    flat = inputs["flattened_patches"].to(DEVICE)
    attn = inputs.get("attention_mask")
    attn = attn.to(DEVICE) if attn is not None else None

    enc = model.get_encoder()(
        flattened_patches=flat,
        attention_mask=attn,
        output_hidden_states=False,
        return_dict=True
    )
    feat = enc.last_hidden_state.mean(dim=1)  # (1, D)
    if normalize:
        feat = feat / (feat.norm(dim=1, keepdim=True) + 1e-12)
    return feat.squeeze(0).detach().cpu().numpy()  # (D,)

# ======================= Metrics =================================
def euclidean_distance(vec1, vec2):
    return np.linalg.norm(vec1 - vec2)

def calculate_total_intra_class_alignment(features_by_class):
    total_distance, total_pairs = 0.0, 0
    for feats in features_by_class.values():
        n = len(feats)
        if n < 2:
            continue
        for i in range(n):
            for j in range(i+1, n):
                total_distance += euclidean_distance(feats[i], feats[j])
        total_pairs += n * (n - 1) // 2
    overall_alignment = (total_distance / total_pairs) if total_pairs else 0.0
    return overall_alignment, overall_alignment**2, total_distance, total_pairs

def calculate_uniformity_metric(features_by_class, t_values=(1,5,10)):
    total_pairs = sum(len(f)*(len(f)-1)//2 for f in features_by_class.values())
    if total_pairs == 0:
        return {t: float('-inf') for t in t_values}

    metrics = {}
    for t in t_values:
        exp_sum = 0.0
        for feats in features_by_class.values():
            n = len(feats)
            if n < 2:
                continue
            for i in range(n):
                for j in range(i+1, n):
                    d = euclidean_distance(feats[i], feats[j])
                    exp_sum += math.exp(-(d**2) * t)
        avg_exp = exp_sum / total_pairs
        metrics[t] = float(np.log(avg_exp + 1e-12))
    return metrics

