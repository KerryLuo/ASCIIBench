import numpy as np

def euclidean_distance(vec1, vec2):
    return np.linalg.norm(vec1 - vec2)

def calculate_exp_sum_of_distances(features_by_class, t):
    exp_sum_of_distances = 0
    for _, features in features_by_class.items():
        for i in range(len(features)):
            for j in range(i + 1, len(features)):
                distance = euclidean_distance(features[i], features[j])
                exp_sum_of_distances += np.exp(-1 * distance ** 2 * t)
    return exp_sum_of_distances

def calculate_uniformity_metric(features_by_class, t_values=[1, 5, 10]):
    uniformity_metrics = {}
    total_pairs = sum(len(features) * (len(features) - 1) / 2 for features in features_by_class.values())

    for t in t_values:
        exp_sum_of_distances = calculate_exp_sum_of_distances(features_by_class, t)
        average_exp = exp_sum_of_distances / total_pairs
        uniformity_metric = np.log(average_exp)

        uniformity_metrics[t] = uniformity_metric

    return uniformity_metrics

